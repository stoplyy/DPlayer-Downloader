// Generates runtime constants only. Publisher credentials never enter the ZIP.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const config = JSON.parse(readFileSync(new URL('release/config.json', root), 'utf8'));
const manifest = JSON.parse(readFileSync(new URL('extensions/edge/manifest.json', root), 'utf8'));
manifest.version = config.extensionVersion;
manifest.minimum_chrome_version = config.minimumBrowserVersion;
const runtime = Object.fromEntries(['productName', 'hostVersion', 'minimumHostVersion', 'protocolVersion', 'nativeHostName', 'releaseUrl', 'supportUrl', 'privacyUrl'].map(key => [key, config[key]]));
const outputs = {
  'extensions/edge/manifest.json': `${JSON.stringify(manifest, null, 2)}\n`,
  'extensions/shared/release_config.mjs': `// Generated by tools/sync-release.mjs; edit release/config.json.\nexport const RELEASE = Object.freeze(${JSON.stringify(runtime, null, 2)});\n`,
  'host/release_version.py': `# Generated by tools/sync-release.mjs; edit release/config.json.\nHOST_VERSION = ${JSON.stringify(config.hostVersion)}\n`,
};
for (const [path, content] of Object.entries(outputs)) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== content) throw new Error(`Stale generated file: ${path}`);
  } else writeFileSync(url, content);
}
